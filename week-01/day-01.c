/* First C Program */

#include <stdio.h>
// Preprocessor directive: Includes the standard input/output header file.
// 전처리기 지시문: 표준 입출력 헤더 파일을 포함한다.

int main(void)
// main is the starting point of a C program.
// main은 C 프로그램이 시작되는 함수이다.
// int: Returns an integer value.
// void: Takes no arguments.
{
    printf("Hello world!");
    // printf is a function that prints text to the screen.
    // printf는 화면에 글자를 출력하는 함수이다.

    return 0;
    // Returns 0 to show that the program ended successfully.
    // 프로그램이 정상적으로 종료되었음을 나타낸다.
}
